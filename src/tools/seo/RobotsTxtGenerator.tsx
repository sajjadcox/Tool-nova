import React, { useState } from 'react';
import { Bot, Copy, Check, Download, ShieldCheck, RefreshCw } from 'lucide-react';
import { CopyButton } from '../../components/common/CopyButton';

export const RobotsTxtGenerator: React.FC = () => {
  const [allowAll, setAllowAll] = useState<boolean>(true);
  const [crawlDelay, setCrawlDelay] = useState<string>('0');
  const [sitemapUrl, setSitemapUrl] = useState<string>('https://example.com/sitemap.xml');
  const [disallowedPaths, setDisallowedPaths] = useState<string>('/admin/\n/private/\n/tmp/\n/login/');
  const [bots, setBots] = useState<{ [key: string]: boolean }>({
    Googlebot: true,
    Bingbot: true,
    Baiduspider: true,
    YandexBot: true,
    DuckDuckBot: true,
    Applebot: true,
    facebookexternalhit: true,
    GPTBot: false, // Disallow AI scraper by default
    CCBot: false
  });

  const toggleBot = (bot: string) => {
    setBots(prev => ({ ...prev, [bot]: !prev[bot] }));
  };

  const generateRobotsTxt = () => {
    const lines: string[] = ['# robots.txt generated by ToolNova SEO Suite', ''];

    // Main user agent block
    lines.push('User-agent: *');
    if (allowAll) {
      lines.push('Allow: /');
    }

    const paths = disallowedPaths.split('\n').map(p => p.trim()).filter(Boolean);
    paths.forEach(p => {
      lines.push(`Disallow: ${p}`);
    });

    if (parseInt(crawlDelay, 10) > 0) {
      lines.push(`Crawl-delay: ${crawlDelay}`);
    }
    lines.push('');

    // Specific bot rules
    Object.entries(bots).forEach(([bot, allowed]) => {
      if (!allowed) {
        lines.push(`User-agent: ${bot}`);
        lines.push('Disallow: /');
        lines.push('');
      }
    });

    if (sitemapUrl.trim()) {
      lines.push(`Sitemap: ${sitemapUrl.trim()}`);
    }

    return lines.join('\n');
  };

  const content = generateRobotsTxt();

  const handleDownload = () => {
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robots.txt';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="bg-white dark:bg-[#131C31] border border-slate-200 dark:border-slate-800 rounded-2xl p-5 sm:p-6 space-y-5">
        <div className="flex items-center justify-between pb-3 border-b border-slate-200 dark:border-slate-800">
          <h3 className="text-sm font-bold text-slate-900 dark:text-white flex items-center gap-2">
            <Bot className="w-4 h-4 text-teal-600 dark:text-teal-400" />
            <span>Robots.txt Generator for Webmasters</span>
          </h3>
          <button
            type="button"
            onClick={handleDownload}
            className="px-3.5 py-1.5 rounded-xl bg-teal-600 hover:bg-teal-700 text-white font-bold text-xs flex items-center gap-1.5 transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download robots.txt</span>
          </button>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
          <div className="space-y-4 text-xs">
            <div className="space-y-1">
              <label className="font-bold text-slate-700 dark:text-slate-300">
                Sitemap URL (Recommended for Google indexing):
              </label>
              <input
                type="url"
                value={sitemapUrl}
                onChange={(e) => setSitemapUrl(e.target.value)}
                placeholder="https://example.com/sitemap.xml"
                className="w-full px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-900 text-slate-800 dark:text-slate-200 font-mono text-xs"
              />
            </div>

            <div className="space-y-1">
              <label className="font-bold text-slate-700 dark:text-slate-300">
                Disallowed Paths (One per line):
              </label>
              <textarea
                rows={4}
                value={disallowedPaths}
                onChange={(e) => setDisallowedPaths(e.target.value)}
                placeholder="/admin/\n/private/"
                className="w-full px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-900 text-slate-800 dark:text-slate-200 font-mono text-xs"
              />
            </div>

            <div className="space-y-2">
              <label className="font-bold text-slate-700 dark:text-slate-300">
                Search Engine Bot Permissions:
              </label>
              <div className="grid grid-cols-2 gap-2">
                {Object.entries(bots).map(([bot, allowed]) => (
                  <label key={bot} className="flex items-center gap-2 p-2 rounded-lg bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 cursor-pointer">
                    <input
                      type="checkbox"
                      checked={allowed}
                      onChange={() => toggleBot(bot)}
                      className="accent-teal-600 rounded"
                    />
                    <span className="font-semibold text-slate-700 dark:text-slate-300">{bot}</span>
                  </label>
                ))}
              </div>
            </div>
          </div>

          {/* Generated Code Preview */}
          <div className="space-y-2">
            <div className="flex items-center justify-between text-xs">
              <span className="font-bold text-slate-700 dark:text-slate-300">Generated robots.txt Preview:</span>
              <CopyButton textToCopy={content} label="Copy Output" />
            </div>
            <pre className="p-4 rounded-xl bg-slate-900 text-teal-300 font-mono text-xs h-72 overflow-y-auto leading-relaxed border border-slate-800">
              {content}
            </pre>
          </div>
        </div>
      </div>
    </div>
  );
};
